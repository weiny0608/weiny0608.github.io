"""Read audited annual operating figures from TSMC's SEC exhibits."""

import re
from datetime import date, timedelta
from urllib.error import HTTPError


def _twd_thousands(cells):
    amounts = []
    for cell in cells:
        value = cell.removeprefix('$')
        negative = value.startswith('(') and value.endswith(')')
        digits = value[1:-1] if negative else value
        if not re.fullmatch(r'\d{1,3}(?:,\d{3})*', digits):
            return None
        amounts.append(int(digits.replace(',', '')) * (-1000 if negative else 1000))
    return tuple(amounts)


def _annual_tsm_statement(document, year):
    from sync_reported_earnings import FilingTables, clean

    filing = FilingTables(document)
    lead = clean(' '.join(filing.text[:350]))[:6000]
    expected_title = (f'Taiwan Semiconductor Manufacturing Company Limited and Subsidiaries '
                      f'Consolidated Financial Statements for the Years Ended December 31, {year} and {year - 1}')
    audit = re.search(r'\bwe have audited the accompanying consolidated financial statements\b', lead, re.I)
    if (expected_title.lower() not in lead.lower() or not audit
            or not re.search(r'International Financial Reporting Standards \(IFRS\).*?Financial Supervisory '
                             r'Commission of the Republic of China', lead[audit.start():], re.I)):
        return None

    revenue, operating, capex = set(), set(), set()
    years = [str(year), str(year - 1)]
    for context, raw_rows in filing.tables:
        statement = re.search(r'CONSOLIDATED STATEMENTS OF (COMPREHENSIVE INCOME|CASH FLOWS) '
                              r'\(In Thousands of New Taiwan Dollars(?:, Except Earnings Per Share)?\)$', context, re.I)
        if not statement:
            continue
        rows = [[cell[0] for cell in row if cell[0]] for row in raw_rows]
        rows = [row for row in rows if row]
        if not rows or rows[0] != years:
            continue
        if statement[1].upper() == 'COMPREHENSIVE INCOME':
            if rows[1:2] != [['Amount', '%', 'Amount', '%']]:
                continue
            for label, *cells in rows[2:]:
                if re.fullmatch(r'NET REVENUE(?: \(Notes? [^)]*\))?', label, re.I) and len(cells) == 4:
                    revenue.add(_twd_thousands(cells[::2]))
            continue

        section = None
        acquiring = False
        for label, *cells in rows[1:]:
            if label.startswith('CASH FLOWS FROM '):
                section = label
                acquiring = False
            elif section == 'CASH FLOWS FROM OPERATING ACTIVITIES':
                if label == 'Net cash generated by operating activities' and len(cells) == 2:
                    operating.add(_twd_thousands(cells))
            elif section == 'CASH FLOWS FROM INVESTING ACTIVITIES':
                if not cells:
                    acquiring = label == 'Acquisitions of:'
                elif acquiring and label == 'Property, plant and equipment' and len(cells) == 2:
                    capex.add(_twd_thousands(cells))

    # The cash-flow statement presents purchases as negative cash outflows.
    if any(len(values) != 1 or None in values for values in (revenue, operating, capex)):
        return None
    revenues, operating_flows, investments = (next(iter(values)) for values in (revenue, operating, capex))
    if min(revenues) <= 0 or max(investments) > 0:
        return None
    return [
        {'periodStart': f'{fiscal_year}-01-01', 'periodEnd': f'{fiscal_year}-12-31', 'revenue': sales,
         'operatingCashFlow': cash_flow, 'capitalExpenditure': -investment, 'value': cash_flow + investment}
        for fiscal_year, sales, cash_flow, investment in zip(map(int, years), revenues, operating_flows, investments)
    ]


def tsm_annual_operating(client, cik, today):
    """Return two comparable calendar years from the newest audited TSMC Form 6-K exhibit."""
    from sync_reported_earnings import DATA, filing_exhibits, iso_date, recent_filings

    submissions = client.json(f'{DATA}/submissions/CIK{str(cik).zfill(10)}.json')
    if 'TSM' not in (submissions.get('tickers') or []) or 'NYSE' not in (submissions.get('exchanges') or []):
        return None
    filings = []
    for filed, filing in recent_filings(submissions, today - timedelta(days=460)):
        end = iso_date(filing['reportDate'])
        if (filing['form'] == '6-K' and end and (end.month, end.day) == (12, 31)
                and filed <= today and 1 <= (filed - end).days <= 140):
            filings.append((end, filed, filing))
    # The issuer's financial-statement submissions use a distinct primary title.
    filings.sort(key=lambda item: (item[0], item[2]['primaryDocument'].lower().startswith('tsm-fsx'), item[1]), reverse=True)
    for end, filed, filing in filings:
        try:
            for url in filing_exhibits(client, cik, filing):
                history = _annual_tsm_statement(client.get(url), end.year)
                if history:
                    return {'history': history, 'sourceName': '台積電年度合併財報（SEC 6-K）',
                            'sourceUrl': url, 'reportDate': filed.isoformat()}
        except HTTPError as exc:
            if exc.code != 404:
                raise
    return None
